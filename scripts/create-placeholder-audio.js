#!/usr/bin/env node
/**
 * Creates tiny silent MP3 placeholder files so Remotion can load
 * without errors before the real voiceovers are generated.
 *
 * Usage: node scripts/create-placeholder-audio.js
 */

const fs = require("fs");
const path = require("path");

const VOICEOVER_DIR = path.join(__dirname, "..", "public", "voiceover");

const FILES = [
  "s1-man-order.mp3",
  "s1-langgraph.mp3",
  "s1-crewai.mp3",
  "s1-openai.mp3",
  "s1-man-deadpan.mp3",
  "s2-crewai.mp3",
  "s2-langgraph.mp3",
  "s2-openai.mp3",
  "s2-man.mp3",
  "s3-man-question.mp3",
  "s3-langgraph.mp3",
  "s3-crewai.mp3",
  "s3-openai.mp3",
  "s3-man-joke.mp3",
  "s3-all-langgraph.mp3",
  "s3-all-crewai.mp3",
  "s3-all-openai.mp3",
];

// Minimal valid MP3 frame (silence) -- 144 bytes MPEG1 Layer3 mono 128kbps
// This is a single silent MPEG audio frame
const SILENT_MP3 = Buffer.from([
  0xFF, 0xFB, 0x90, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x49, 0x6E, 0x66, 0x6F,
  0x00, 0x00, 0x00, 0x0F, 0x00, 0x00, 0x00, 0x01,
  0x00, 0x00, 0x00, 0x90, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
]);

fs.mkdirSync(VOICEOVER_DIR, { recursive: true });

let created = 0;
for (const file of FILES) {
  const filePath = path.join(VOICEOVER_DIR, file);
  if (!fs.existsSync(filePath)) {
    fs.writeFileSync(filePath, SILENT_MP3);
    created++;
  }
}

console.log(`Created ${created} placeholder audio files (${FILES.length - created} already existed)`);
